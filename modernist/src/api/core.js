import api from './client'

export const getCountries = (params) => api.get('/countries/', { params })
export const createCountry = (data) => api.post('/countries/', data)
export const updateCountry = (id, data) => api.patch(`/countries/${id}/`, data)
export const deleteCountry = (id) => api.delete(`/countries/${id}/`)
export const ensureNationalTeam = (id) => api.post(`/countries/${id}/ensure-national-team/`)
export const getCountryProfile = (id, params) => api.get(`/countries/${id}/profile/`, { params })
export const getCountrySquad = (id, params) => api.get(`/countries/${id}/squad/`, { params })
export const getCountryProgression = (id, params) => api.get(`/countries/${id}/progression/`, { params })
export const getEvents = (params) => api.get('/events/', { params })
export const getFinaPointsPreview = (params) => api.get('/fina-points/', { params })
export const getMe = () => api.get('/auth/me/')
export const login = (username, password) => api.post('/auth/login/', { username, password })
export const register = (data) => api.post('/auth/register/', data)
export const createOrgAccount = (data) => api.post('/auth/org-accounts/', data)
// Invite links: admin makes one for an entity, the entity opens it to create its account
export const getInvites = (params) => api.get('/auth/invites/', { params })
export const createInvite = (kind, target) => api.post('/auth/invites/', { kind, target })
export const revokeInvite = (id) => api.post(`/auth/invites/${id}/revoke/`)
export const deleteInvite = (id) => api.delete(`/auth/invites/${id}/`)
export const openInvite = (token) => api.get(`/auth/invites/open/${encodeURIComponent(token)}/`)
export const acceptInvite = (token, data) => api.post(`/auth/invites/open/${encodeURIComponent(token)}/`, data)
export const getFeatures = () => api.get('/features/')
export const updateFeatures = (data) => api.patch('/features/', data)
export const getChangeLog = (params) => api.get('/changelog/', { params })
export const revertChange = (id) => api.post(`/changelog/${id}/revert/`)
