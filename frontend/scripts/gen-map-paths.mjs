// One-off generator: builds accurate SVG path silhouettes for the medal
// breakdown icons from Natural Earth data (world-atlas package).
// Run: node scripts/gen-map-paths.mjs > src/assets/mapPaths.js
import fs from 'fs'
import * as topojson from 'topojson-client'
import { geoMercator, geoPath } from 'd3-geo'

const world = JSON.parse(fs.readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)))

const AFRICA = ['012', '024', '204', '072', '854', '108', '132', '120', '140', '148', '174', '178', '180', '384', '262', '818', '226', '232', '748', '231', '266', '270', '288', '324', '624', '404', '426', '430', '434', '450', '454', '466', '478', '480', '504', '508', '516', '562', '566', '646', '678', '686', '690', '694', '706', '710', '728', '729', '834', '768', '788', '800', '894', '716', '732']
const ASIA = ['004', '051', '031', '048', '050', '064', '096', '116', '156', '196', '268', '356', '360', '364', '368', '376', '392', '400', '398', '414', '417', '418', '422', '458', '462', '496', '104', '524', '408', '512', '586', '275', '608', '634', '643', '682', '702', '410', '144', '760', '158', '762', '764', '626', '792', '795', '784', '860', '704', '887']
const ARAB = ['012', '048', '174', '262', '818', '368', '400', '414', '422', '434', '478', '504', '512', '275', '634', '682', '706', '729', '760', '788', '784', '887', '732']
const GCC = ['048', '414', '512', '634', '682', '784']

const regions = { AFRICA_PATH: AFRICA, ASIA_PATH: ASIA, ARAB_PATH: ARAB, GCC_PATH: GCC }

let out = '// Auto-generated by scripts/gen-map-paths.mjs from Natural Earth 110m data.\n// Accurate region silhouettes, each fitted to a 64x64 viewBox.\n'
for (const [name, ids] of Object.entries(regions)) {
  const geoms = world.objects.countries.geometries.filter(g => ids.includes(String(g.id)))
  const merged = topojson.merge(world, geoms)
  // Rotate Asia so Russia's antimeridian crossing doesn't smear the map
  const proj = geoMercator()
  if (name === 'ASIA_PATH') proj.rotate([-95, 0])
  proj.fitExtent([[2, 2], [62, 62]], merged)
  let d = geoPath(proj)(merged)
  // Round coordinates to 1 decimal to keep the bundle small
  d = d.replace(/(\d+\.\d+)/g, m => (+m).toFixed(1))
  out += `export const ${name} = '${d}'\n`
}
fs.writeFileSync(new URL('../src/assets/mapPaths.js', import.meta.url), out)
console.log('written src/assets/mapPaths.js')
